/**
 * Integrates identity erasure with WordPress privacy APIs.
 */
class IC_Identity_Privacy {
	/**
	 * Registers WordPress privacy and deletion hooks.
	 */
	public static function init() {
		add_filter( 'wp_privacy_personal_data_exporters', array( __CLASS__, 'exporters' ) );
		add_filter( 'wp_privacy_personal_data_erasers', array( __CLASS__, 'erasers' ), 5 );
		add_filter( 'map_meta_cap', array( __CLASS__, 'map_meta_cap' ), 10, 4 );
		add_filter( 'ic_orders_customer_create', array( __CLASS__, 'allow_customer_create' ), 10, 2 );
		add_action( 'deleted_user', array( __CLASS__, 'deleted_user' ), 5, 3 );
		add_action( 'digital-order-summary', array( __CLASS__, 'order_summary_notice' ) );
	}

	/**
	 * Shows the privacy lifecycle for an order in its existing summary box.
	 *
	 * @param int $order_id Order ID.
	 */
	public static function order_summary_notice( $order_id ) {
		$order_id = absint( $order_id );
		$order    = get_post( $order_id );
		// phpcs:ignore WordPress.WP.Capabilities.Unknown -- edit_digital_order is the registered object capability for al_digital_orders.
		if ( ! $order || 'al_digital_orders' !== $order->post_type || ! current_user_can( 'edit_digital_order', $order_id ) ) {
			return;
		}

		$message = self::durable_order_privacy_message( $order_id );
		if ( '' === $message ) {
			$user_id = absint( get_post_meta( $order_id, '_customer_id', true ) );
			$message = self::transient_order_privacy_message( $user_id );
		}
		if ( '' === $message ) {
			return;
		}

		$html = ic_html_util();
		// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- The message is escaped when built and the wrapper is generated by ic_html_util().
		echo $html->div( $html->p( $message ), 'al-box info ic-order-privacy-status', null, array( 'role' => 'status' ) );
	}

	/**
	 * Builds a message from durable order lifecycle metadata.
	 *
	 * @param int $order_id Order ID.
	 * @return string
	 */
	private static function durable_order_privacy_message( $order_id ) {
		$removed = get_post_meta( $order_id, '_ic_removed_customer', true );
		if ( ! is_string( $removed ) || ! preg_match( '/^removed:[a-f0-9]{12}$/', $removed ) ) {
			return '';
		}

		$severed = self::gmt_time( get_post_meta( $order_id, '_ic_customer_severed_gmt', true ) );
		$erased  = self::gmt_time( get_post_meta( $order_id, '_ic_identity_erased_gmt', true ) );
		$retain  = self::gmt_time( get_post_meta( $order_id, '_ic_identity_retain_until', true ) );
		$prefix  = esc_html__( 'Privacy removal: the customer account link has been removed.', 'ecommerce-product-catalog' );
		if ( $severed ) {
			$prefix = sprintf(
				/* translators: %s: localized account-link removal date and time. */
				esc_html__( 'Privacy removal: the customer account link was removed on %s.', 'ecommerce-product-catalog' ),
				self::time_markup( $severed )
			);
		}
		$facts_now   = esc_html__( 'Non-identifying order and accounting facts remain for record keeping.', 'ecommerce-product-catalog' );
		$facts_after = esc_html__( 'Non-identifying order and accounting facts will remain after erasure.', 'ecommerce-product-catalog' );

		if ( $erased ) {
			return $prefix . ' ' . sprintf(
				/* translators: %s: localized identity-erasure date and time. */
				esc_html__( 'Configured invoice identity was fully erased on %s.', 'ecommerce-product-catalog' ),
				self::time_markup( $erased )
			) . ' ' . $facts_now;
		}
		if ( $retain ) {
			if ( time() >= $retain->getTimestamp() ) {
				return $prefix . ' ' . sprintf(
					/* translators: %s: localized statutory identity-erasure deadline. */
					esc_html__( 'Configured invoice identity remains; its retention deadline passed on %s, and erasure is awaiting the daily privacy sweep.', 'ecommerce-product-catalog' ),
					self::time_markup( $retain )
				) . ' ' . $facts_after;
			}
			return $prefix . ' ' . sprintf(
				/* translators: %s: localized statutory identity-erasure deadline. */
				esc_html__( 'Configured invoice identity remains during statutory retention and will be fully erased after %s.', 'ecommerce-product-catalog' ),
				self::time_markup( $retain )
			) . ' ' . $facts_after;
		}

		return $prefix . ' ' . esc_html__( 'The full-erasure deadline is unavailable because this is a legacy or inconsistent privacy record. Configured invoice identity may still remain.', 'ecommerce-product-catalog' ) . ' ' . $facts_after;
	}

	/**
	 * Builds a message from a matching active erasure queue or core request.
	 *
	 * @param int $user_id Linked customer user ID.
	 * @return string
	 */
	private static function transient_order_privacy_message( $user_id ) {
		if ( ! $user_id ) {
			return '';
		}
		$queue = get_option( IC_Identity_Erasure::QUEUE_OPTION, array() );
		$job   = isset( $queue[ 'user_' . $user_id ] ) ? $queue[ 'user_' . $user_id ] : array();
		if ( is_array( $job ) && absint( isset( $job['user_id'] ) ? $job['user_id'] : 0 ) === $user_id ) {
			return esc_html__( 'Privacy removal is being processed. The customer account link has not yet been removed from this order.', 'ecommerce-product-catalog' );
		}

		$requests = get_posts(
			array(
				'post_type'      => 'user_request',
				'post_status'    => array( 'request-confirmed', 'request-pending' ),
				'post_name__in'  => array( 'remove_personal_data' ),
				'author'         => $user_id,
				'fields'         => 'ids',
				'posts_per_page' => 1,
				'orderby'        => 'date',
				'order'          => 'DESC',
				'no_found_rows'  => true,
			)
		);
		if ( ! $requests ) {
			return '';
		}
		$status = get_post_status( reset( $requests ) );
		if ( 'request-confirmed' === $status ) {
			return esc_html__( 'A privacy-removal request has been confirmed and is awaiting administrator erasure. No order data has been removed yet.', 'ecommerce-product-catalog' );
		}
		if ( 'request-pending' === $status ) {
			return esc_html__( 'A privacy-removal request is awaiting customer confirmation. No order data has been removed yet.', 'ecommerce-product-catalog' );
		}
		return '';
	}

	/**
	 * Strictly parses a stored UTC date.
	 *
	 * @param mixed $value Stored value.
	 * @return DateTimeImmutable|false
	 */
	private static function gmt_time( $value ) {
		if ( ! is_string( $value ) || ! preg_match( '/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/', $value ) ) {
			return false;
		}
		$date   = DateTimeImmutable::createFromFormat( '!Y-m-d H:i:s', $value, new DateTimeZone( 'UTC' ) );
		$errors = DateTimeImmutable::getLastErrors();
		if ( ! $date || ( is_array( $errors ) && ( $errors['warning_count'] || $errors['error_count'] ) ) || $date->format( 'Y-m-d H:i:s' ) !== $value ) {
			return false;
		}
		return $date;
	}

	/**
	 * Formats a UTC date as localized accessible time markup.
	 *
	 * @param DateTimeImmutable $date UTC date.
	 * @return string
	 */
	private static function time_markup( $date ) {
		$format = trim( get_option( 'date_format' ) . ' ' . get_option( 'time_format' ) );
		return ic_html_util()->tag(
			'time',
			esc_html( wp_date( $format, $date->getTimestamp(), wp_timezone() ) ),
			array( 'datetime' => $date->format( 'Y-m-d\TH:i:s\Z' ) )
		);
	}

	/**
	 * Registers the identity exporter.
	 *
	 * @param array $exporters Existing exporters.
	 * @return array
	 */
	public static function exporters( $exporters ) {
		$exporters['ic-identity'] = array(
			'exporter_friendly_name' => __( 'Orders and entitlements', 'ecommerce-product-catalog' ),
			'callback'               => array( __CLASS__, 'export' ),
		);
		return $exporters;
	}

	/**
	 * Registers the identity eraser.
	 *
	 * @param array $erasers Existing erasers.
	 * @return array
	 */
	public static function erasers( $erasers ) {
		$erasers['ic-identity'] = array(
			'eraser_friendly_name' => __( 'Orders and entitlements', 'ecommerce-product-catalog' ),
			'callback'             => array( __CLASS__, 'erase' ),
		);
		return $erasers;
	}

	/**
	 * Exports order and entitlement references for an email address.
	 *
	 * @param string $email_address User email address.
	 * @param int    $page          Export page.
	 * @return array
	 */
	public static function export( $email_address, $page = 1 ) {
		$user = get_user_by( 'email', $email_address );
		if ( ! $user || 1 < absint( $page ) ) {
			return array(
				'data' => array(),
				'done' => true,
			);
		}
		$data = array();
		foreach ( IC_Identity_Erasure::sources() as $key => $source ) {
			if ( 'post' !== $source['type'] ) {
				continue;
			}
			$ids = get_posts(
				array(
					'post_type'      => $source['post_type'],
					'post_status'    => 'any',
					'fields'         => 'ids',
					'posts_per_page' => -1,
					// phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_key -- Privacy export must locate records by their registered customer metadata.
					'meta_key'       => $source['customer_meta'],
					// phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_value -- Privacy export must locate records by the requesting user's identity.
					'meta_value'     => $user->ID,
				)
			);
			foreach ( $ids as $id ) {
				$data[] = array(
					'group_id'    => 'ic-identity',
					'group_label' => __( 'Orders and entitlements', 'ecommerce-product-catalog' ),
					'item_id'     => $key . '-' . $id,
					'data'        => array(
						array(
							'name'  => __( 'Record', 'ecommerce-product-catalog' ),
							'value' => '#' . $id,
						),
						array(
							'name'  => __( 'Retention', 'ecommerce-product-catalog' ),
							'value' => $source['statutory'] ? __( 'Invoice identity is retained until the statutory deadline.', 'ecommerce-product-catalog' ) : __( 'Removed on erasure.', 'ecommerce-product-catalog' ),
						),
					),
				);
			}
		}
		return array(
			'data' => $data,
			'done' => true,
		);
	}

	/**
	 * Starts or advances identity erasure for an email address.
	 *
	 * @param string $email_address User email address.
	 * @param int    $page          Eraser page.
	 * @return array
	 */
	public static function erase( $email_address, $page = 1 ) {
		$user = get_user_by( 'email', $email_address );
		if ( ! $user ) {
			return array(
				'items_removed'  => false,
				'items_retained' => false,
				'messages'       => array(),
				'done'           => true,
			);
		}
		$page = absint( $page );
		if ( 1 < $page && ! get_option( IC_Identity_Erasure::QUEUE_OPTION, array() ) ) {
			return array(
				'items_removed'  => true,
				'items_retained' => true,
				'messages'       => array(),
				'done'           => true,
			);
		}
		$job_id = ic_identity_erase_user( $user->ID );
		if ( is_wp_error( $job_id ) ) {
			return array(
				'items_removed'  => false,
				'items_retained' => true,
				'messages'       => (array) $job_id->get_error_data(),
				'done'           => true,
			);
		}
		$result = ic_identity_erasure_step( $job_id );
		return array(
			'items_removed'  => true,
			'items_retained' => true,
			'messages'       => array( __( 'Statutory invoice identity is retained until its configured deadline.', 'ecommerce-product-catalog' ) ),
			'done'           => ! empty( $result['done'] ),
		);
	}

	/**
	 * Blocks direct user deletion while entitlements remain live.
	 *
	 * @param array  $caps    Required primitive capabilities.
	 * @param string $cap    Requested meta capability.
	 * @param int    $user_id Acting user ID.
	 * @param array  $args    Capability arguments.
	 * @return array
	 */
	public static function map_meta_cap( $caps, $cap, $user_id, $args ) {
		if ( 'delete_user' !== $cap || empty( $args[0] ) || ! apply_filters( 'ic_identity_block_delete_on_entitlement', true, absint( $args[0] ) ) ) {
			return $caps;
		}
		if ( ic_identity_erasure_blockers( absint( $args[0] ) ) ) {
			return array( 'do_not_allow' );
		}
		return $caps;
	}

	/**
	 * Forces erasure after WordPress deletes a user.
	 *
	 * @param int          $user_id  Deleted user ID.
	 * @param int|null     $reassign Reassignment user ID.
	 * @param WP_User|null $user    Deleted user object.
	 */
	public static function deleted_user( $user_id, $reassign = null, $user = null ) {
		unset( $reassign );
		$role            = $user instanceof WP_User && $user->roles ? reset( $user->roles ) : '';
		$anonymise_stats = apply_filters( 'ic_stats_anonymise_on_user_delete', true, absint( $user_id ) );
		$job_id          = ic_identity_erase_user(
			$user_id,
			array(
				'forced'          => true,
				'user_role'       => $role,
				'anonymise_stats' => $anonymise_stats,
			)
		);
		while ( true ) {
			$result = ic_identity_erasure_step( $job_id );
			if ( ! $result ) {
				break;
			}
			if ( ! empty( $result['done'] ) ) {
				break;
			}
		}
	}

	/**
	 * Prevents severed orders from being linked to a customer again.
	 *
	 * @param bool $allow    Whether customer creation is allowed.
	 * @param int  $order_id Order ID.
	 * @return bool
	 */
	public static function allow_customer_create( $allow, $order_id ) {
		return ic_identity_record_is_severed( $order_id ) ? false : $allow;
	}
}
